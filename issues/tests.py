class PublicAccountabilityAndTriageViewsTest(TestCase):
    def setUp(self):
        self.client = Client()
        self.ward = Ward.objects.create(
            ward_number="Ward 19",
            name="Banani",
            city_corporation="Dhaka North City Corporation (DNCC)",
            councillor_name="Md. Mofizur Rahman",
            center_latitude=23.7937,
            center_longitude=90.4066
        )
        self.official = CustomUser.objects.create_user(
            username='ward_officer',
            password='password123',
            role='OFFICIAL',
            assigned_ward=self.ward
        )
        self.issue = Issue.objects.create(
            title="Sewer Leak on Road 4",
            description="Sewage overflow on main road.",
            category="Water Leak",
            severity="High",
            ward=self.ward,
            latitude=23.7938,
            longitude=90.4045,
            upvotes_count=12,
            status="In Progress"
        )

    def test_index_view_renders_successfully(self):
        response = self.client.get(reverse('index'))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Fix My City")
        self.assertContains(response, "Ward 19")

    def test_accountability_board_renders(self):
        response = self.client.get(reverse('accountability_board'))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Ward Accountability Board")
        self.assertContains(response, "Md. Mofizur Rahman")

    def test_authority_dashboard_renders(self):
        self.client.login(username='ward_officer', password='password123')
        response = self.client.get(reverse('authority_dashboard'))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Municipal Authority & Ward Console")

    def test_download_pdf_petition_view(self):
        response = self.client.get(reverse('download_petition_pdf', args=[self.issue.id]))
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response['Content-Type'], 'application/pdf')
        self.assertIn("attachment; filename=", response['Content-Disposition'])

    def test_ajax_upvote_endpoint(self):
        initial_upvotes = self.issue.upvotes_count
        response = self.client.post(reverse('api_upvote', args=[self.issue.id]))
        self.assertEqual(response.status_code, 200)
        data = response.json()
        self.assertEqual(data['status'], 'success')
        self.assertEqual(data['upvotes'], initial_upvotes + 1)

    def test_official_status_triage_audit_log(self):
        self.client.login(username='ward_officer', password='password123')
        post_data = {
            'status': 'Resolved',
            'resolution_notes': 'Repairs finished by DNCC squad.',
        }
        response = self.client.post(
            reverse('update_issue_status', args=[self.issue.id]),
            data=post_data,
            follow=True
        )
        self.assertEqual(response.status_code, 200)
        self.issue.refresh_from_db()
        self.assertEqual(self.issue.status, 'Resolved')
        self.assertIsNotNone(self.issue.resolved_at)

        # Verify audit history
        latest_log = StatusHistory.objects.filter(issue=self.issue).first()
        self.assertIsNotNone(latest_log)
        self.assertEqual(latest_log.new_status, 'Resolved')
        self.assertEqual(latest_log.changed_by, self.official)

    def test_reverse_geocode_endpoint(self):
        response = self.client.get(reverse('api_reverse_geocode'), {'lat': '23.7937', 'lng': '90.4066'})
        self.assertEqual(response.status_code, 200)
        data = response.json()
        self.assertIn(data['status'], ['success', 'fallback'])
        self.assertIn('clean_address', data)

